"""Build the experiment with pinned tools; Python 3.10+ and JDK 21, no device access."""
import hashlib
import json
import os
import shutil
import subprocess
import tempfile
import urllib.request
import zipfile
from pathlib import Path

from rule_config import ROOT, load_rules
from verify_apk import verify_apk


def run(args):
    subprocess.run([str(x) for x in args], cwd=ROOT, check=True)


def java_tool(name):
    suffix = '.exe' if os.name == 'nt' else ''
    java_home = os.environ.get('JAVA_HOME')
    result = Path(java_home) / 'bin' / (name + suffix) if java_home else shutil.which(name)
    if not result or not Path(result).is_file():
        raise RuntimeError('Install JDK 21 and set JAVA_HOME (missing ' + name + ')')
    return str(result)


def dependencies():
    cache = ROOT / '.cache/tools'
    cache.mkdir(parents=True, exist_ok=True)
    entries = json.loads((ROOT / 'tools/dependencies.json').read_text(encoding='utf-8'))
    result = {}
    for name, spec in entries.items():
        dest = cache / name
        if not dest.exists():
            print('Downloading ' + name, flush=True)
            request = urllib.request.Request(spec['url'], headers={'User-Agent': 'TabletCompletion-build/0.7.0'})
            with urllib.request.urlopen(request, timeout=90) as response:
                payload = response.read()
            if hashlib.sha256(payload).hexdigest() != spec['sha256']:
                raise RuntimeError('Downloaded dependency checksum mismatch: ' + name)
            dest.write_bytes(payload)
        if hashlib.sha256(dest.read_bytes()).hexdigest() != spec['sha256']:
            raise RuntimeError('Cached dependency checksum mismatch: ' + str(dest))
        result[name] = dest
    return result


def generate_rules(destination):
    entries = []
    for app in load_rules():
        args = [json.dumps(app[k]) for k in ('package', 'homeActivity', 'searchActivity')]
        args += [str(app[k]).lower() for k in ('searchLaunchFallback', 'manualKeyboard', 'blockAds')]
        entries.append('        new AppRule(' + ', '.join(args) + ')')
    source = '''package dev.tabletcompletion.keyboard;
// Generated by tools/build.py from rules/apps.json. Do not edit generated output.
public final class AppRules {
    private static final AppRule[] RULES = {
%s
    };
    public static AppRule find(String packageName) {
        for (AppRule rule : RULES) if (rule.packageName.equals(packageName)) return rule;
        return null;
    }
}
''' % ',\n'.join(entries)
    destination.write_text(source, encoding='utf-8', newline='\n')


def main():
    java, javac, jar = [java_tool(x) for x in ('java', 'javac', 'jar')]
    deps = dependencies()
    build_root = ROOT / 'build'
    build_root.mkdir(exist_ok=True)
    # Each build uses an isolated directory, so stale classes cannot enter a new APK.
    build = Path(tempfile.mkdtemp(prefix='run-', dir=build_root))
    classes, dex = build / 'classes', build / 'dex'
    classes.mkdir()
    dex.mkdir()
    generated = build / 'AppRules.java'
    generate_rules(generated)
    api_jar = build / 'libxposed-api.jar'
    with zipfile.ZipFile(deps['libxposed-api-102.aar']) as archive:
        api_jar.write_bytes(archive.read('classes.jar'))
    sources = sorted((ROOT / 'module/src').rglob('*.java'))
    classpath = os.pathsep.join(map(str, (deps['android.jar'], api_jar)))
    run([javac, '--release', '8', '-encoding', 'UTF-8', '-cp', classpath, '-d', classes, *sources, generated])
    test_classes = build / 'test-classes'
    test_classes.mkdir()
    test_classpath = os.pathsep.join(map(str, (classes, api_jar)))
    run([javac, '--release', '8', '-encoding', 'UTF-8', '-cp', test_classpath, '-d', test_classes,
         ROOT / 'tests/java/HookFlowTest.java', ROOT / 'tests/java/AdBlockerTest.java'])
    run([java, '-cp', os.pathsep.join((str(test_classes), test_classpath)), 'HookFlowTest'])
    run([java, '-cp', os.pathsep.join((str(test_classes), test_classpath)), 'AdBlockerTest'])
    module_jar = build / 'module.jar'
    run([jar, 'cf', module_jar, '-C', classes, '.'])
    run([java, '-cp', deps['r8.jar'], 'com.android.tools.r8.D8', '--min-api', '27',
         '--lib', deps['android.jar'], '--classpath', api_jar, '--output', dex, module_jar])
    stage = build / 'apk'
    stage.mkdir()
    for name in ('AndroidManifest.xml', 'apktool.yml'):
        shutil.copyfile(ROOT / 'module' / name, stage / name)
    shutil.copytree(ROOT / 'module/res', stage / 'res')
    shutil.copyfile(dex / 'classes.dex', stage / 'classes.dex')
    framework = ROOT / '.cache/apktool-framework'
    framework.mkdir(parents=True, exist_ok=True)
    unsigned = build / 'tablet-completion.apk'
    run([java, '-jar', deps['apktool.jar'], 'b', stage, '-p', framework, '-o', unsigned])
    # Apktool can discard META-INF during packaging. Insert modern metadata before signing.
    with zipfile.ZipFile(unsigned, 'a', compression=zipfile.ZIP_DEFLATED) as archive:
        for source in sorted((ROOT / 'module/META-INF/xposed').iterdir()):
            archive.writestr('META-INF/xposed/' + source.name, source.read_bytes())
        archive.writestr('META-INF/xposed/scope.list',
                         ''.join(app['package'] + '\n' for app in load_rules()))
    signed = build / 'signed'
    run([java, '-jar', deps['signer.jar'], '--apks', unsigned, '--out', signed])
    apk_files = list(signed.glob('*-aligned-debugSigned.apk'))
    if len(apk_files) != 1:
        raise RuntimeError('Expected exactly one signed APK')
    run([java, '-jar', deps['signer.jar'], '--apks', apk_files[0], '--onlyVerify'])
    verify_apk(apk_files[0], {app['package'] for app in load_rules()})

    helper_classes, helper_dex = build / 'helper-classes', build / 'helper-dex'
    helper_classes.mkdir()
    helper_dex.mkdir()
    run([javac, '--release', '8', '-encoding', 'UTF-8', '-cp', deps['android.jar'], '-d', helper_classes,
         ROOT / 'tools/ReloadRules.java', ROOT / 'module/src/dev/tabletcompletion/keyboard/AppRule.java', generated])
    helper_jar = build / 'helper.jar'
    run([jar, 'cf', helper_jar, '-C', helper_classes, '.'])
    run([java, '-cp', deps['r8.jar'], 'com.android.tools.r8.D8', '--min-api', '27',
         '--lib', deps['android.jar'], '--output', helper_dex, helper_jar])
    dist = ROOT / 'dist'
    dist.mkdir(exist_ok=True)
    shutil.copyfile(apk_files[0], dist / 'tablet-completion-debug.apk')
    shutil.copyfile(helper_dex / 'classes.dex', dist / 'reload.dex')
    checksums = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                 for p in (dist / 'tablet-completion-debug.apk', dist / 'reload.dex')}
    (dist / 'SHA256SUMS').write_text(''.join(f'{v}  {k}\n' for k, v in checksums.items()), encoding='utf-8')
    print('Built APK and one-shot reload helper in ' + str(dist))


if __name__ == '__main__':
    main()
